// Bundles the migration files into src/migrations.gen.js (a Worker has no file system).
//   node scripts/gen-migrations.js
import { writeFileSync } from 'node:fs';
import { readMigrationFiles } from '../src/db.js';
writeFileSync(new URL('../src/migrations.gen.js', import.meta.url), `// GENERATED by scripts/gen-migrations.js. Do not edit.\nexport const MIGRATIONS = ${JSON.stringify(readMigrationFiles(), null, 2)};\n`);
console.log('src/migrations.gen.js written');
